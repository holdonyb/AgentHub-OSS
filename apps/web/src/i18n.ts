type TranslationKey = keyof typeof translations['zh-CN'];

function interpolate(template: string, values?: TemplateValues) {
  if (!values) return template;
  return Object.entries(values).reduce(
    (current, [key, value]) => current.replaceAll(`{${key}}`, String(value)),
    template,
  );
}

export function t(locale: LocaleCode, key: TranslationKey, values?: TemplateValues) {
  const zh = translations['zh-CN'][key];
  const template = locale === 'en-US' ? translations['en-US'][key] : locale === 'zh-TW' ? toTraditional(zh) : zh;
  return interpolate(template, values);
}

export function localeLabel(locale: LocaleCode, value: LocaleCode) {
  if (value === 'en-US') return t(locale, 'enUS');
  if (value === 'zh-TW') return t(locale, 'zhTW');
  return t(locale, 'zhCN');
}

export function themeModeLabel(locale: LocaleCode, value: 'dark' | 'light') {
  return value === 'light' ? t(locale, 'light') : t(locale, 'dark');
}

export function voiceModeLabel(locale: LocaleCode, value: 'streaming' | 'standard') {
  return value === 'streaming' ? t(locale, 'streaming') : t(locale, 'standard');
}

export function voiceLanguageLabel(locale: LocaleCode, value: string) {
  if (value === 'en-US') return t(locale, 'english');
  if (value === 'zh-TW') return t(locale, 'zhTW');
  return t(locale, 'chinese');
}

export function formatRelativeTime(locale: LocaleCode, value?: string | null, parseDate?: (input?: string | null) => Date | null) {
  const parsed = parseDate ? parseDate(value) : value ? new Date(value) : null;
  if (!parsed || Number.isNaN(parsed.getTime())) return '';
  const delta = Date.now() - parsed.getTime();
  const minutes = Math.max(1, Math.round(delta / 60000));
  if (minutes < 60) return t(locale, 'minutesAgo', { count: minutes });
  const hours = Math.round(minutes / 60);
  if (hours < 24) return t(locale, 'hoursAgo', { count: hours });
  const days = Math.round(hours / 24);
  return t(locale, 'daysAgo', { count: days });
}

export function statusText(locale: LocaleCode, status: string) {
  const labels: Record<string, TranslationKey> = {
    ready: 'statusReady',
    queued: 'statusQueued',
    running: 'statusRunning',
    needs_reply: 'statusNeedsReply',
    failed: 'statusFailed',
    cancelled: 'statusCancelled',
    terminated: 'statusTerminated',
    online: 'statusOnline',
    degraded: 'statusDegraded',
    offline: 'statusOffline',
    succeeded: 'statusSucceeded',
  };
  const key = labels[status];
  return key ? t(locale, key) : status;
}
