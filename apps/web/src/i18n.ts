const zhHantPairs = Object.entries(zhHantMap).sort((left, right) => right[0].length - left[0].length);

export function isLocaleCode(value: unknown): value is LocaleCode {
  return typeof value === 'string' && supportedLocales.includes(value as LocaleCode);
}

export function toTraditional(input: string) {
  return zhHantPairs.reduce((text, [from, to]) => text.replaceAll(from, to), input);
}

export function pickLocale(locale: LocaleCode, zhHans: string, en: string, zhHant?: string) {
  if (locale === 'en-US') return en;
  if (locale === 'zh-TW') return zhHant ?? toTraditional(zhHans);
  return zhHans;
}

